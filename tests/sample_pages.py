"""
עמודים לדוגמה, בנויים ביד, באותו מבנה שה-OCR מחזיר (מילה + מיקום).
כך אפשר לבדוק את ה-Classifier והפרסרים בלי PDF ובלי Tesseract.
"""


def w(text, x, y, width=30):
    return {"text": text, "x0": float(x), "x1": float(x + width), "top": float(y), "bottom": float(y + 10)}


def type_a_page():
    """הדו"ח הפשוט. עמודות מימין לשמאל: תאריך | יום | כניסה | יציאה | סה"כ | הערות."""
    words = [
        # כרטיסי הסיכום: תווית, ומתחתיה הערך
        w("לתשלום", 100, 40), w("890.00", 100, 55),
        w("מחיר", 220, 40), w("40.00", 220, 55),
        w("חודשיות", 340, 40), w("22.25", 340, 55),
        w("ימי", 460, 40), w("3", 460, 55),
        # כותרות הטבלה
        w("תאריך", 520, 80), w("שעת", 380, 80), w("שעת", 300, 80), w("הערות", 120, 80),
    ]
    rows = [
        ("01/09/22", "חמישי", "8:10", "16:40", "8.50", ""),
        ("02/09/22", "שישי", "", "", "", "ערב חג"),
        ("03/09/22", "שבת", "", "", "", ""),
        ("04/09/22", "ראשון", "8:00", "15:30", "7.50", ""),
        ("05/09/22", "שני", "9:05", "15:20", "6.25", ""),
    ]
    for i, (d, day, entry, exit_, total, note) in enumerate(rows):
        y = 100 + 20 * i
        words += [w(d, 520, y), w(day, 460, y)]
        for text, x in ((entry, 380), (exit_, 300), (total, 220)):
            if text:
                words.append(w(text, x, y))
        for j, part in enumerate(note.split()[::-1]):
            words.append(w(part, 100 + 30 * j, y))
    return words


def type_b_page():
    """הדו"ח המפורט. מימין לשמאל: תאריך | יום | מקום | כניסה | יציאה | הפסקה | סה"כ | 100 | 125 | 150 | שבת."""
    words = [
        w("בע\"מ", 300, 20), w("אדם", 340, 20), w("כח", 380, 20), w("הכשר", 420, 20), w("ג.ע.", 460, 20),
        w("תאריך", 560, 80), w("מקום", 440, 80), w("הפסקה", 260, 80),
        w("100%", 160, 80), w("125%", 120, 80), w("150%", 80, 80), w("שבת", 40, 80),
    ]
    rows = [
        ("01/02/23", "רביעי", "08:00", "16:30", "00:30", ["8.00", "8.00", "0.00", "0.00", "0.00"]),
        ("02/02/23", "חמישי", "07:30", "18:00", "00:30", ["10.00", "8.00", "2.00", "0.00", "0.00"]),
        ("03/02/23", "שישי", "", "", "", []),
        ("04/02/23", "שבת", "", "", "", []),
        ("05/02/23", "ראשון", "08:12", "16:47", "00:30", ["8.08", "8.00", "0.08", "0.00", "0.00"]),
    ]
    for i, (d, day, entry, exit_, brk, numbers) in enumerate(rows):
        y = 100 + 20 * i
        words += [w(d, 560, y), w("יום", 520, y), w(day, 490, y), w("גונן", 440, y)]
        for text, x in ((entry, 380), (exit_, 320), (brk, 260)):
            if text:
                words.append(w(text, x, y))
        for text, x in zip(numbers, (200, 160, 120, 80, 40)):
            words.append(w(text, x, y))
    return words
